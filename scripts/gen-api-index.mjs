#!/usr/bin/env node
/**
 * gen-api-index.mjs — build the /api index from the library itself.
 *
 *   npm run gen:api
 *
 * The index is GENERATED, never hand-maintained, for the same reason
 * `check:exports` exists in the library repo: a hand-written list of a 174-member
 * surface drifts the moment someone adds a mark, and nothing catches it. Here the
 * three inputs are all things that already have to be right:
 *
 *   1. the library's RUNTIME exports  — what you can actually call
 *   2. src/vocabulary.js              — every factory's option vocabulary, which
 *                                       the library's own gates already hold to
 *                                       both the .d.ts and the factory bodies
 *   3. the docs' own api.tsx files    — which page documents each name, harvested
 *                                       so the index deep-links instead of guessing
 *
 * A new mark therefore appears in the index with its options and a link, with no
 * edit here. If it has no deep-dive page yet, it still appears — listed without a
 * link, which is the honest signal that the page is missing.
 *
 * Output: lib/api-index.generated.ts (committed, so the site builds without the
 * library present — but regenerated by `npm run deploy:pages`).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const docsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libRoot = path.resolve(docsRoot, '../elicitjs');
const outFile = path.join(docsRoot, 'lib/api-index.generated.ts');

// Namespaces that are the GRAMMAR — what can appear in a spec. `authoring` is
// deliberately excluded: it is the kit you build new vocabulary FROM, not
// vocabulary itself, and mixing the two is the exact confusion the library's
// namespace split was made to prevent.
const GRAMMAR = ['plot', 'elements', 'edit', 'constraints', 'guides', 'widgets', 'format'];

// Reader-facing prose: see ../STYLE.md. State what you call it for, not how the
// engine treats it.
const BLURB = {
    plot: 'Marks draw the rows of your dataset.',
    elements: 'Chart elements draw a scale: axes, grids and legends.',
    edit: 'Edits map a gesture back through a scale to write a column.',
    constraints: 'Constraints are rules over the dataset. Each one rejects or repairs every edit.',
    guides: 'Guides draw reference lines and interaction state. They never write data.',
    widgets: 'Widgets are complete survey instruments. Each returns a spec.',
    format: 'Formatters turn a value into a string for a label or an axis.',
};

const lib = await import(path.join(libRoot, 'src/index.js'));
const vocab = await import(path.join(libRoot, 'src/vocabulary.js'));
const libVersion = JSON.parse(
    fs.readFileSync(path.join(libRoot, 'package.json'), 'utf8'),
).version;

// ---- Where is each name documented? ----------------------------------------
// Every docs page carries an api.tsx whose entries name the factories it covers
// (`'bar(options) · barY(options) · barX(options)'`). Harvesting those identifiers
// gives a real name → route map, so the index links to the page that actually
// explains a thing rather than to a guessed URL.
function harvestDocLinks() {
    // THREE TIERS, because a headline names one thing and mentions several, and the
    // two failure modes are different. Harvesting every token made the link
    // first-wins by directory-walk order (`constraints.clamp` → /scales). Ranking by
    // "leading identifier" alone was not enough either: pages document OPTIONS with
    // bare-word headlines too, so an option called `clamp` still outranked the
    // constraint called `clamp`.
    //
    // The discriminator is whether the headline is a CALL. An entry that documents a
    // factory shows its signature (`clamp({ min, max })`, `bar(options) · barY(…)`);
    // an entry that documents an option is a bare word (`orientation`, `clamp`).
    //
    //   call  an identifier immediately followed by `(` — this page documents the thing
    //   bare  the leading identifier of a `·`/`/`-separated part — `axis · axisX · axisY`
    //   weak  any other identifier in any headline — a mention, kept as a last resort
    const call = new Map();
    const bare = new Map();
    const weak = new Map();
    const walk = (dir) => {
        for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
            const p = path.join(dir, e.name);
            if (e.isDirectory()) { walk(p); continue; }
            if (e.name !== 'api.tsx') continue;
            const rel = path.relative(path.join(docsRoot, 'app'), dir).replace(/\\/g, '/');
            const route = rel === '' ? '/' : '/' + rel;
            const src = fs.readFileSync(p, 'utf8');
            const add = (map, name) => { if (!map.has(name)) map.set(name, route); };
            for (const m of src.matchAll(/name:\s*['"]([^'"]+)['"]/g)) {
                const headline = m[1];
                const ID = '[A-Za-z][A-Za-z0-9]*(?:\\.[A-Za-z][A-Za-z0-9]*)*';
                for (const c of headline.matchAll(new RegExp(ID + '(?=\\s*\\()', 'g'))) add(call, c[0]);
                for (const part of headline.split(/[·/,]/)) {
                    const lead = part.trim().match(new RegExp('^(' + ID + ')'));
                    if (lead) add(bare, lead[1]);
                }
                for (const id of headline.matchAll(new RegExp(ID, 'g'))) add(weak, id[0]);
            }
        }
    };
    walk(path.join(docsRoot, 'app'));
    return { call, bare, weak };
}
const { call: callLinks, bare: bareLinks, weak: weakLinks } = harvestDocLinks();

// Heuristics get a handful wrong, and a curated map is more honest than another
// tier. These are names that appear in a call-shaped MENTION on some other page
// before the page that documents them: `/editing/gestures` writes `axis(` about an
// edit option, `/scales` writes `legend(` while explaining channels. Checked first,
// so a wrong link is one line to fix rather than a heuristic to re-tune.
const OVERRIDES = {
    'elements.axis': '/marks/axes',
    'elements.legend': '/marks/legend',
};

// A namespace's own landing page, used when a member has no entry of its own.
const NAMESPACE_FALLBACK = {
    plot: null,             // marks are per-page; no single page is right
    elements: null,        // per-page like marks: axis→/marks/axes, legend→/marks/legend
    edit: '/editing',
    constraints: '/constraints',
    guides: '/guides',
    widgets: '/widgets',
    format: '/scales',
};

// Resolution order: the page that has this name as an entry SUBJECT, then the
// namespace's own landing page, and only then a page that merely mentions it. The
// fallback outranks a weak match because "the constraints page" is a better answer
// for `constraints.clamp` than "a page whose option table says clamp".
function linkFor(qualified, name, ns) {
    // A call signature beats everything: that page documents the factory. The
    // namespace's own landing page beats a bare-word match, because "the constraints
    // page" is a better answer for `constraints.clamp` than "a page with an option
    // called clamp". Bare beats weak, and plot has no landing page — so a mark with
    // only a bare match (`rule · ruleX · ruleY`) still lands on the right page.
    return OVERRIDES[qualified]
        || callLinks.get(qualified)
        || callLinks.get(name)
        || NAMESPACE_FALLBACK[ns]
        || bareLinks.get(qualified)
        || bareLinks.get(name)
        || weakLinks.get(qualified)
        || weakLinks.get(name)
        || null;
}

// ---- Options ---------------------------------------------------------------
// Each kind keeps its vocabulary in a differently-named map, and edits are keyed
// by their DOTTED type (`line.draw`), which is the same key the edit stamps as
// `type` — so the lookup here is the same identity the engine uses.
function optionsFor(ns, bare, dotted) {
    const universal = {
        plot: vocab.MARK_UNIVERSAL_OPTIONS,
        elements: vocab.ELEMENT_UNIVERSAL_OPTIONS,
        guides: vocab.GUIDE_UNIVERSAL_OPTIONS,
        edit: vocab.EDIT_UNIVERSAL_OPTIONS,
    }[ns] || [];
    const own = {
        plot: vocab.MARK_OPTIONS?.[bare],
        elements: vocab.ELEMENT_OPTIONS?.[bare],
        guides: vocab.GUIDE_OPTIONS?.[bare],
        edit: vocab.EDIT_OPTIONS?.[dotted] ?? vocab.EDIT_OPTIONS?.[bare],
        constraints: vocab.CONSTRAINT_OPTIONS?.[bare],
    }[ns];
    if (!own && !universal.length) return { own: [], universal: [] };
    return { own: own ? [...own] : [], universal: [...universal] };
}

// ---- Walk the namespaces ---------------------------------------------------
const entries = [];

for (const ns of GRAMMAR) {
    const bag = lib[ns];
    if (!bag) { console.warn(`gen-api-index: no namespace ${ns} on the library`); continue; }

    for (const key of Object.keys(bag).sort()) {
        const value = bag[key];

        // A scoped namespace (edit.line, edit.network, edit.stack) is an object of
        // factories, and its members' dotted names ARE their `type`.
        if (value && typeof value === 'object' && !Array.isArray(value)) {
            for (const sub of Object.keys(value).sort()) {
                if (typeof value[sub] !== 'function') continue;
                const dotted = `${key}.${sub}`;
                entries.push({
                    namespace: ns,
                    group: `${ns}.${key}`,
                    name: sub,
                    qualified: `${ns}.${dotted}`,
                    call: `${ns}.${dotted}(options)`,
                    ...optionsFor(ns, sub, dotted),
                    docs: linkFor(`${ns}.${dotted}`, dotted, ns),
                });
            }
            continue;
        }

        if (typeof value !== 'function') continue;
        entries.push({
            namespace: ns,
            group: ns,
            name: key,
            qualified: `${ns}.${key}`,
            call: `${ns}.${key}(options)`,
            ...optionsFor(ns, key, key),
            docs: linkFor(`${ns}.${key}`, key, ns),
        });
    }
}

// Top-level exports that are not namespaces: Elicit, setWarnings, themes, …
const topLevel = Object.keys(lib)
    .filter((k) => !GRAMMAR.includes(k) && k !== 'authoring')
    .sort()
    .map((k) => ({
        name: k,
        kind: typeof lib[k],
        docs: callLinks.get(k) || bareLinks.get(k) || weakLinks.get(k) || null,
    }));

// ---- Emit ------------------------------------------------------------------
const byNamespace = GRAMMAR.map((ns) => ({
    namespace: ns,
    blurb: BLURB[ns],
    count: entries.filter((e) => e.namespace === ns).length,
}));

const banner = `// GENERATED by scripts/gen-api-index.mjs — do not edit.
// Regenerate with \`npm run gen:api\`; \`npm run deploy:pages\` does it for you.
// Source of truth: the library's runtime exports + src/vocabulary.js.
`;

const body = `${banner}
export type ApiIndexEntry = {
  namespace: string;
  group: string;
  name: string;
  qualified: string;
  call: string;
  own: string[];
  universal: string[];
  docs: string | null;
};

export type ApiNamespace = { namespace: string; blurb: string; count: number };

export const API_LIBRARY_VERSION = ${JSON.stringify(libVersion)};
export const API_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const API_NAMESPACES: ApiNamespace[] = ${JSON.stringify(byNamespace, null, 2)};
export const API_TOP_LEVEL = ${JSON.stringify(topLevel, null, 2)};
export const API_INDEX: ApiIndexEntry[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(outFile, body);

const linked = entries.filter((e) => e.docs).length;
console.log(`gen-api-index: ${entries.length} members across ${GRAMMAR.length} namespaces ` +
    `(${linked} linked, ${entries.length - linked} without a page), ` +
    `${topLevel.length} top-level exports → lib/api-index.generated.ts`);
