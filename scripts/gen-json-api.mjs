#!/usr/bin/env node
/**
 * gen-json-api.mjs — the JSON form of every keyword, for the API tables'
 * JavaScript | JSON switch.
 *
 *   npm run gen:api
 *
 * Read from the library's own JSON grammar (src/json, the SPEC_* tables in
 * src/vocabulary.js), so the API tables say what `compile()` accepts.
 *
 * An API entry names what it documents with `json: ['plot.bar', 'channel', …]`:
 * a keyword (`<namespace>.<keyword>`) or an owner from SPEC_FUNCTIONS. This
 * script fails on a name the library does not have.
 *
 * Output: lib/json-api.generated.ts (committed, like the API index).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const docsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libRoot = path.resolve(docsRoot, '../elicitjs');
const outFile = path.join(docsRoot, 'lib/json-api.generated.ts');

const { NAMESPACES } = await import(path.join(libRoot, 'src/json/index.js'));
const { keywordTables } = await import(path.join(libRoot, 'src/json/keywords.js'));
const { ownersOf } = await import(path.join(libRoot, 'src/json/compile.js'));
const { SPEC_FUNCTIONS, SPEC_POSITIONAL, SPEC_SLOTS } = await import(path.join(libRoot, 'src/vocabulary.js'));

/** Where a descriptor of each namespace sits. */
const PLACE = {
  plot: 'in "marks"',
  elements: 'in "elements"',
  edit: 'in "edits", or a channel\'s "edit"',
  constraints: 'in "constraints"',
  guides: 'in "guides"',
  looks: 'in "looks"',
  widgets: 'under "widget"',
  format: 'in "format" or "tickFormat"',
  when: 'in "when"',
};

const keywords = {};
for (const [ns, table] of Object.entries(keywordTables(NAMESPACES))) {
  for (const type of table.keys()) {
    const id = `${ns}.${type}`;
    keywords[id] = {
      type,
      place: PLACE[ns],
      positional: SPEC_POSITIONAL[id] || [],
      // Where its function options are listed, most specific first.
      owners: ownersOf(ns, type).filter((owner) => SPEC_FUNCTIONS[owner]),
    };
  }
}

// Every option that takes a function, by owner: a keyword (`guides.rule`), a kind
// (`mark`, `axis`, `channel`) or `spec`. 'edit' has none of its own, but an
// entry can name it for `when` and `constrain`.
const owners = { ...SPEC_FUNCTIONS, edit: {} };

// Options that hold descriptors and also take a function in their place.
const slots = Object.fromEntries(
  Object.entries(SPEC_SLOTS).filter(([, s]) => s.fn).map(([key, s]) => [key, s.fn]),
);

// ---- Every `json: [...]` in the API tables names something real -------------
const problems = [];
let named = 0;
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === 'api.tsx') {
      const src = fs.readFileSync(p, 'utf8');
      for (const m of src.matchAll(/\bjson:\s*\[([^\]]*)\]/g)) {
        for (const id of m[1].matchAll(/['"]([^'"]+)['"]/g)) {
          named++;
          if (!keywords[id[1]] && !owners[id[1]]) problems.push(`${path.relative(docsRoot, p)}: json names "${id[1]}", which is not a keyword or an owner`);
        }
      }
    }
  }
};
walk(path.join(docsRoot, 'app'));
if (problems.length) {
  console.error(`gen-json-api: ${problems.length} unknown name(s):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

/** One entry per line, so a diff shows what changed. */
const lines = (obj) => `{\n${Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n}`;

const body = `// GENERATED by scripts/gen-json-api.mjs — do not edit.
// Regenerate with \`npm run gen:api\`. Source of truth: the library's src/json and
// the SPEC_* tables in src/vocabulary.js.

/** A function option's \`expr\` variables, 'ctx' for the keys of one context
 *  object, or 'fn' for a named function only. '*' is any option. */
export type JsonSignature = string[] | string;

export type JsonKeyword = {
  type: string;
  place: string;
  positional: string[];
  owners: string[];
};

export const JSON_KEYWORDS: Record<string, JsonKeyword> = ${lines(keywords)};

export const JSON_OWNERS: Record<string, Record<string, JsonSignature>> = ${lines(owners)};

export const JSON_SLOTS: Record<string, JsonSignature> = ${lines(slots)};
`;
fs.writeFileSync(outFile, body);
console.log(`gen-json-api: ${Object.keys(keywords).length} keywords, ${Object.keys(owners).length} owners, ` +
  `${named} names in the API tables → lib/json-api.generated.ts`);
